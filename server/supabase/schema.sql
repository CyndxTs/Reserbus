-- =====================================================================
-- RESERBUS  ·  PostgreSQL / Supabase  (v2 con atributos)
-- Reutilizable: borra todo el schema y lo recrea (DROP ... CASCADE).
-- Todos los TIMESTAMPTZ se guardan en UTC; la conversión a hora local
-- se hace con pais.desfase_utc_min (vía provincia -> terminal).
-- El correo y la contraseña NO se guardan aquí: viven en auth.users (Supabase Auth).
-- =====================================================================
BEGIN;

DROP SCHEMA IF EXISTS reserbus CASCADE;
CREATE SCHEMA reserbus;
SET LOCAL search_path TO reserbus;

CREATE TYPE tipo_trabajador AS ENUM ('CHOFER', 'ADMINISTRATIVO');
CREATE TYPE tipo_documento  AS ENUM ('DNI', 'CE', 'PASAPORTE');
CREATE TYPE estado_viaje    AS ENUM ('PENDIENTE', 'CONFIRMADO', 'CANCELADO', 'EXPIRADO');

-- ---------------------------------------------------------------------
-- UBICACIÓN
-- ---------------------------------------------------------------------
CREATE TABLE pais (
  id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(80) NOT NULL UNIQUE,
  desfase_utc_min  SMALLINT NOT NULL            -- minutos respecto a UTC (Perú = -300)
);

CREATE TABLE provincia (                         -- "provincia" también para otros países
  id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pais   INT NOT NULL REFERENCES pais (id),
  nombre    VARCHAR(80) NOT NULL,
  UNIQUE (id_pais, nombre)
);

CREATE TABLE terminal (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_provincia  INT NOT NULL REFERENCES provincia (id),
  nombre        VARCHAR(100) NOT NULL,
  direccion     VARCHAR(200) NOT NULL           -- el distrito va aquí, sin tabla aparte
);

CREATE TABLE tramo (
  id                   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_terminal_origen   INT NOT NULL REFERENCES terminal (id),
  id_terminal_destino  INT NOT NULL REFERENCES terminal (id),
  CHECK (id_terminal_origen <> id_terminal_destino),
  UNIQUE (id_terminal_origen, id_terminal_destino)
);

-- ---------------------------------------------------------------------
-- ACTORES  (cada uno se enlaza a su cuenta de Supabase Auth con auth_id)
-- ---------------------------------------------------------------------
CREATE TABLE administrador (                     -- sysadmin de la plataforma
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id    UUID NOT NULL UNIQUE REFERENCES auth.users (id),
  nombres    VARCHAR(80) NOT NULL,
  apellidos  VARCHAR(80) NOT NULL
);

CREATE TABLE empresa (
  id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre  VARCHAR(100) NOT NULL UNIQUE,
  activa  BOOLEAN NOT NULL DEFAULT TRUE         -- el sysadmin puede desactivarla
);

CREATE TABLE trabajador (                        -- pertenece a UNA empresa
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id     UUID NOT NULL UNIQUE REFERENCES auth.users (id),
  id_empresa  INT NOT NULL REFERENCES empresa (id),
  tipo        tipo_trabajador NOT NULL,
  nombres     VARCHAR(80) NOT NULL,
  apellidos   VARCHAR(80) NOT NULL,
  activo      BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (id, id_empresa, tipo)                  -- destino de FKs compuestas
);

CREATE TABLE viajero (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id    UUID NOT NULL UNIQUE REFERENCES auth.users (id),
  nombres    VARCHAR(80) NOT NULL,
  apellidos  VARCHAR(80) NOT NULL
);

-- ---------------------------------------------------------------------
-- FLOTA, ASIENTOS Y TARIFAS (todo por empresa)
-- ---------------------------------------------------------------------
CREATE TABLE tipo_bus (                          -- bus de 1 piso, pasillo al medio
  id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa         INT NOT NULL REFERENCES empresa (id),
  nombre             VARCHAR(60) NOT NULL,
  filas              SMALLINT NOT NULL CHECK (filas > 0),
  asientos_por_fila  SMALLINT NOT NULL CHECK (asientos_por_fila >= 2 AND asientos_por_fila % 2 = 0),
                                                 -- mitad a cada lado del pasillo: 4 = 2+2 (A B | C D)
  total_asientos     INT GENERATED ALWAYS AS (filas * asientos_por_fila) STORED,
  UNIQUE (id, id_empresa),
  UNIQUE (id_empresa, nombre)
);

CREATE TABLE tipo_asiento (                      -- lo crea un trabajador administrativo
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa    INT NOT NULL REFERENCES empresa (id),
  nombre        VARCHAR(60) NOT NULL,
  tarifa_extra  NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (tarifa_extra >= 0),
  UNIQUE (id, id_empresa),
  UNIQUE (id_empresa, nombre)
);

-- Qué filas del tipo de bus son de qué tipo de asiento (ej. filas 1-3 = "Cama")
-- Pendiente de validar a nivel app: que los rangos de un mismo tipo_bus no se solapen.
CREATE TABLE tipo_bus_has_tipo_asiento (
  id_tipo_bus      INT NOT NULL,
  id_tipo_asiento  INT NOT NULL,
  id_empresa       INT NOT NULL,
  fila_desde       SMALLINT NOT NULL CHECK (fila_desde > 0),
  fila_hasta       SMALLINT NOT NULL,
  PRIMARY KEY (id_tipo_bus, fila_desde),
  CHECK (fila_hasta >= fila_desde),
  FOREIGN KEY (id_tipo_bus, id_empresa)     REFERENCES tipo_bus (id, id_empresa),
  FOREIGN KEY (id_tipo_asiento, id_empresa) REFERENCES tipo_asiento (id, id_empresa)
);

CREATE TABLE tarifa (                            -- precio base por tipo de bus y tramo
  id_tipo_bus  INT NOT NULL REFERENCES tipo_bus (id),
  id_tramo     INT NOT NULL REFERENCES tramo (id),
  monto_base   NUMERIC(10,2) NOT NULL CHECK (monto_base >= 0),
  PRIMARY KEY (id_tipo_bus, id_tramo)
);

CREATE TABLE bus (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa   INT NOT NULL REFERENCES empresa (id),
  id_tipo_bus  INT NOT NULL,
  placa        VARCHAR(10) NOT NULL UNIQUE,
  activo       BOOLEAN NOT NULL DEFAULT TRUE,
  FOREIGN KEY (id_tipo_bus, id_empresa) REFERENCES tipo_bus (id, id_empresa),
  UNIQUE (id, id_empresa)
);

CREATE TABLE servicio (
  id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE bus_has_servicio (
  id_bus       INT NOT NULL REFERENCES bus (id),
  id_servicio  INT NOT NULL REFERENCES servicio (id),
  PRIMARY KEY (id_bus, id_servicio)
);

-- ---------------------------------------------------------------------
-- RUTAS, HORARIOS Y PLANES (por empresa)
-- Sin tiempo de espera en paradas: la llegada a un terminal = salida del siguiente tramo.
-- ---------------------------------------------------------------------
CREATE TABLE ruta (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa  INT NOT NULL REFERENCES empresa (id),
  nombre      VARCHAR(100) NOT NULL,
  UNIQUE (id, id_empresa),
  UNIQUE (id_empresa, nombre)
);

CREATE TABLE ruta_has_tramo (                    -- secuencia ordenada de tramos
  id_ruta       INT NOT NULL REFERENCES ruta (id),
  id_tramo      INT NOT NULL REFERENCES tramo (id),
  posicion      SMALLINT NOT NULL CHECK (posicion > 0),
  duracion_min  INT NOT NULL CHECK (duracion_min > 0),
  PRIMARY KEY (id_ruta, id_tramo),
  UNIQUE (id_ruta, posicion)
  -- Pendiente de validar a nivel app: destino del tramo N = origen del tramo N+1
);

CREATE TABLE horario (                           -- hora de salida del 1er tramo de la ruta (UTC)
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ruta      INT NOT NULL REFERENCES ruta (id),
  hora_salida  TIME NOT NULL,
  UNIQUE (id_ruta, hora_salida),
  UNIQUE (id, id_ruta)
);

CREATE TABLE plan (                              -- "lista": ruta + horario + buses + choferes
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa  INT NOT NULL,
  id_ruta     INT NOT NULL,
  id_horario  INT NOT NULL,
  activo      BOOLEAN NOT NULL DEFAULT TRUE,     -- solo los activos generan tramos programados
  FOREIGN KEY (id_ruta, id_empresa) REFERENCES ruta (id, id_empresa),
  FOREIGN KEY (id_horario, id_ruta) REFERENCES horario (id, id_ruta),
  UNIQUE (id, id_ruta),
  UNIQUE (id, id_empresa)
);

CREATE TABLE plan_has_bus (
  id_plan     INT NOT NULL,
  id_bus      INT NOT NULL,
  id_empresa  INT NOT NULL,
  PRIMARY KEY (id_plan, id_bus),
  FOREIGN KEY (id_plan, id_empresa) REFERENCES plan (id, id_empresa),
  FOREIGN KEY (id_bus, id_empresa)  REFERENCES bus (id, id_empresa)
);

CREATE TABLE plan_has_trabajador (               -- solo choferes
  id_plan         INT NOT NULL,
  id_trabajador   INT NOT NULL,
  id_empresa      INT NOT NULL,
  tipo            tipo_trabajador NOT NULL DEFAULT 'CHOFER' CHECK (tipo = 'CHOFER'),
  PRIMARY KEY (id_plan, id_trabajador),
  FOREIGN KEY (id_plan, id_empresa)             REFERENCES plan (id, id_empresa),
  FOREIGN KEY (id_trabajador, id_empresa, tipo) REFERENCES trabajador (id, id_empresa, tipo)
);

-- ---------------------------------------------------------------------
-- TRAMO PROGRAMADO = una "arista" concreta: un bus recorriendo un tramo
-- de un plan en una fecha/hora. Es lo que usa el algoritmo de búsqueda
-- y lo que se reserva. Aquí viven los tiempos estimado y real (UTC).
-- ---------------------------------------------------------------------
CREATE TABLE tramo_programado (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_plan           INT NOT NULL,
  id_bus            INT NOT NULL,
  id_ruta           INT NOT NULL,
  id_tramo          INT NOT NULL,
  salida_estimada   TIMESTAMPTZ NOT NULL,
  llegada_estimada  TIMESTAMPTZ NOT NULL,
  salida_real       TIMESTAMPTZ,
  llegada_real      TIMESTAMPTZ,
  CHECK (llegada_estimada > salida_estimada),
  CHECK (llegada_real IS NULL OR salida_real IS NULL OR llegada_real > salida_real),
  FOREIGN KEY (id_plan, id_bus)    REFERENCES plan_has_bus (id_plan, id_bus),
  FOREIGN KEY (id_plan, id_ruta)   REFERENCES plan (id, id_ruta),
  FOREIGN KEY (id_ruta, id_tramo)  REFERENCES ruta_has_tramo (id_ruta, id_tramo),
  UNIQUE (id_plan, id_bus, id_tramo, salida_estimada)
);

-- ---------------------------------------------------------------------
-- VIAJES, PASAJEROS Y PASAJES
-- ---------------------------------------------------------------------
-- "Viaje" = reserva. Nace PENDIENTE y retiene los asientos 10 min (vence_en) mientras el
-- usuario navega; luego pasa a CONFIRMADO, o a CANCELADO (lo cancela el usuario) o
-- EXPIRADO (venció el hold). Cancelar el viaje = cancelar la reserva completa.
CREATE TABLE viaje (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_viajero    INT NOT NULL REFERENCES viajero (id),
  estado        estado_viaje NOT NULL DEFAULT 'PENDIENTE',
  creado_en     TIMESTAMPTZ NOT NULL DEFAULT now(),                         -- UTC
  vence_en      TIMESTAMPTZ NOT NULL DEFAULT now() + INTERVAL '10 minutes', -- fin del hold
  cancelado_en  TIMESTAMPTZ
);

CREATE TABLE pasajero (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_viaje          INT NOT NULL REFERENCES viaje (id),
  nombres           VARCHAR(80) NOT NULL,
  apellidos         VARCHAR(80) NOT NULL,
  tipo_documento    tipo_documento NOT NULL,
  numero_documento  VARCHAR(20) NOT NULL,
  UNIQUE (id, id_viaje),
  UNIQUE (id_viaje, tipo_documento, numero_documento)   -- misma persona no se repite en un viaje
);

CREATE TABLE viaje_has_tramo_programado (        -- las "patas" del viaje, en orden
  id_viaje             INT NOT NULL REFERENCES viaje (id),
  id_tramo_programado  BIGINT NOT NULL REFERENCES tramo_programado (id),
  posicion             SMALLINT NOT NULL CHECK (posicion > 0),
  PRIMARY KEY (id_viaje, id_tramo_programado),
  UNIQUE (id_viaje, posicion)
);

-- Asiento de un pasajero en cada tramo. No hay tabla ASIENTO: el asiento es (fila, columna)
-- y su código es "12A". Pendiente de validar a nivel app: fila <= filas y columna dentro
-- de las primeras asientos_por_fila letras del tipo de bus.
CREATE TABLE pasaje (
  id_pasajero          INT NOT NULL,
  id_viaje             INT NOT NULL,
  id_tramo_programado  BIGINT NOT NULL,
  fila                 SMALLINT NOT NULL CHECK (fila > 0),
  columna              VARCHAR(1) NOT NULL CHECK (columna ~ '^[A-Z]$'),
  codigo_asiento       VARCHAR(4) GENERATED ALWAYS AS (fila::text || columna) STORED,
  id_tipo_asiento      INT NOT NULL REFERENCES tipo_asiento (id),
  precio               NUMERIC(10,2) NOT NULL CHECK (precio >= 0),  -- base + extra, congelado al comprar
  vigente              BOOLEAN NOT NULL DEFAULT TRUE,               -- FALSE al cancelar/expirar el viaje (libera el asiento)
  PRIMARY KEY (id_pasajero, id_tramo_programado),
  FOREIGN KEY (id_pasajero, id_viaje) REFERENCES pasajero (id, id_viaje),
  FOREIGN KEY (id_viaje, id_tramo_programado)
    REFERENCES viaje_has_tramo_programado (id_viaje, id_tramo_programado)
);

-- ---------------------------------------------------------------------
-- ÍNDICES (Postgres no indexa FKs solo)
-- ---------------------------------------------------------------------
CREATE INDEX idx_terminal_provincia    ON terminal (id_provincia);
CREATE INDEX idx_tramo_destino         ON tramo (id_terminal_destino);
CREATE INDEX idx_tramo_prog_busqueda   ON tramo_programado (id_tramo, salida_estimada);
CREATE INDEX idx_tramo_prog_plan_bus   ON tramo_programado (id_plan, id_bus);
CREATE INDEX idx_pasajero_viaje        ON pasajero (id_viaje);
CREATE INDEX idx_viaje_viajero         ON viaje (id_viajero);
CREATE INDEX idx_viaje_pendiente_vence ON viaje (vence_en) WHERE estado = 'PENDIENTE';

-- Un asiento solo puede estar vigente en UN pasaje por tramo programado (anti doble venta).
-- Los pasajes de viajes cancelados/expirados (vigente = FALSE) no cuentan.
CREATE UNIQUE INDEX uq_pasaje_asiento_vigente
  ON pasaje (id_tramo_programado, fila, columna) WHERE vigente;

-- ---------------------------------------------------------------------
-- LIBERACIÓN DE ASIENTOS
-- 1) Trigger: al pasar un viaje a CANCELADO o EXPIRADO, sus pasajes dejan de estar vigentes.
-- 2) expirar_viajes(): marca EXPIRADO los PENDIENTE vencidos. Llamarla desde Express antes de
--    consultar disponibilidad o reservar (o programarla con pg_cron cada minuto).
-- ---------------------------------------------------------------------
CREATE FUNCTION liberar_asientos_viaje() RETURNS trigger
LANGUAGE plpgsql SET search_path = reserbus AS $$
BEGIN
  IF NEW.estado IN ('CANCELADO', 'EXPIRADO') AND OLD.estado NOT IN ('CANCELADO', 'EXPIRADO') THEN
    UPDATE reserbus.pasaje SET vigente = FALSE WHERE id_viaje = NEW.id;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_viaje_libera_asientos
  AFTER UPDATE OF estado ON viaje
  FOR EACH ROW EXECUTE FUNCTION liberar_asientos_viaje();

CREATE FUNCTION expirar_viajes() RETURNS INT
LANGUAGE plpgsql SET search_path = reserbus AS $$
DECLARE n INT;
BEGIN
  UPDATE reserbus.viaje SET estado = 'EXPIRADO'
   WHERE estado = 'PENDIENTE' AND vence_en < now();
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$;

COMMIT;
