DROP FUNCTION IF EXISTS fn_validar_bus_servicio() CASCADE;
CREATE FUNCTION fn_validar_bus_servicio() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_emp_bus INT; v_emp_srv INT;
BEGIN
  SELECT b.id_empresa INTO v_emp_bus FROM bus b WHERE b.id_bus = NEW.id_bus;
  SELECT s.id_empresa INTO v_emp_srv FROM servicio s WHERE s.id_servicio = NEW.id_servicio;
  IF v_emp_srv IS NOT NULL AND v_emp_srv <> v_emp_bus THEN
    RAISE EXCEPTION 'El servicio % pertenece a otra empresa', NEW.id_servicio;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_validar_bus_servicio
  BEFORE INSERT OR UPDATE ON bus_servicio
  FOR EACH ROW EXECUTE FUNCTION fn_validar_bus_servicio();

