-- =====================================================================
-- TAREAS PROGRAMADAS (pg_cron). Si la extensión no está habilitada, el script no falla:
-- habilítala en Dashboard → Database → Extensions y vuelve a correr este bloque.
--  * cada minuto: libera los holds vencidos
--  * diario 05:00 UTC (00:00 Lima): extiende el horizonte de viajes generados
-- =====================================================================
DO $$
BEGIN
  CREATE EXTENSION IF NOT EXISTS pg_cron;
  PERFORM cron.schedule('reserbus_expirar_reservas',   '* * * * *', $job$SELECT public.fn_expirar_reservas()$job$);
  PERFORM cron.schedule('reserbus_extender_horizonte', '0 5 * * *', $job$SELECT public.fn_extender_horizonte()$job$);
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'pg_cron no disponible (%): programa manualmente fn_expirar_reservas() cada minuto y fn_extender_horizonte() a diario', SQLERRM;
END $$;

