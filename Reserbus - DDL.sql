-- No se puede cambiar el código/zona/tipo ni deshabilitar un asiento que tenga boletos
-- activos en viajes que aún no terminan.
DROP FUNCTION IF EXISTS fn_asiento_proteger() CASCADE;
CREATE FUNCTION fn_asiento_proteger() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.codigo <> OLD.codigo OR NEW.id_zona <> OLD.id_zona
     OR NEW.id_tipo_asiento <> OLD.id_tipo_asiento
     OR (OLD.esta_habilitado AND NOT NEW.esta_habilitado) THEN
    IF EXISTS (SELECT 1 FROM boleto bo JOIN viaje v ON v.id_viaje = bo.id_viaje
               WHERE bo.id_asiento = OLD.id_asiento AND bo.estado = 'ACTIVO'
                 AND v.estado IN ('PROGRAMADO', 'EN_CURSO')) THEN
      RAISE EXCEPTION 'El asiento % tiene boletos activos en viajes pendientes; no se puede modificar', OLD.codigo;
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_asiento_proteger
  BEFORE UPDATE ON asiento
  FOR EACH ROW EXECUTE FUNCTION fn_asiento_proteger();

