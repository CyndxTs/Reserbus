-- ---------- TIPOS ENUM ----------
CREATE TYPE estado_pago        AS ENUM ('PENDIENTE', 'PAGADO', 'RECHAZADO');
CREATE TYPE metodo_pago        AS ENUM ('TARJETA', 'TRANSFERENCIA');
CREATE TYPE estado_viaje       AS ENUM ('PROGRAMADO', 'EN_CURSO', 'FINALIZADO', 'RETRASADO', 'CANCELADO');
CREATE TYPE estado_reserva     AS ENUM ('PAGO_PENDIENTE', 'PAGADA', 'COMPLETADA', 'CANCELADA');
CREATE TYPE tipo_documento     AS ENUM ('DNI', 'PASAPORTE', 'CEDULA', 'CARNET_EXTRANJERIA', 'OTRO');

-- ---------- CATÁLOGOS ----------
CREATE TABLE tipo_de_asiento (
  id_tipo_de_asiento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre             VARCHAR(60) NOT NULL,
  descripcion        VARCHAR(120),
  esta_habilitado    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE servicio (
  id_servicio     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR(20) NOT NULL,
  descripcion     VARCHAR(60),
  esta_habilitado BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------- USUARIOS (vinculados a Supabase Auth) ----------
-- id_auth = auth.users.id. Sin columna de contraseña.
CREATE TABLE viajero (
  id_viajero         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_auth            UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  correo_electronico VARCHAR(120) NOT NULL UNIQUE,
  nombres            VARCHAR(60)  NOT NULL DEFAULT '',
  apellidos          VARCHAR(60)  NOT NULL DEFAULT '',
  telefono           VARCHAR(20),
  fecha_nacimiento   DATE,
  avatar_url         TEXT,
  esta_habilitado    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE empresa (
  id_empresa         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_auth            UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  correo_electronico VARCHAR(120) NOT NULL UNIQUE,
  razon_social       VARCHAR(120) NOT NULL,
  ruc                VARCHAR(11)  NOT NULL UNIQUE,
  descripcion        VARCHAR(200),
  logo_url           TEXT,                 -- antes MEDIUMBLOB; ahora Supabase Storage
  esta_habilitado    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE administrador (
  id_administrador   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_auth            UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  correo_electronico VARCHAR(120) NOT NULL UNIQUE,
  nombres            VARCHAR(60) NOT NULL,
  apellidos          VARCHAR(60) NOT NULL,
  fecha_nacimiento   DATE,
  foto_url           TEXT,                 -- antes MEDIUMBLOB
  esta_habilitado    BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------- FLOTA ----------
CREATE TABLE bus (
  id_bus          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa           VARCHAR(10) NOT NULL,
  marca           VARCHAR(60) NOT NULL,
  modelo          VARCHAR(60) NOT NULL,
  id_empresa      INT NOT NULL REFERENCES empresa(id_empresa),
  esta_habilitado BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_bus_empresa ON bus(id_empresa);

CREATE TABLE bus_servicio (
  id_bus      INT NOT NULL REFERENCES bus(id_bus),
  id_servicio INT NOT NULL REFERENCES servicio(id_servicio),
  PRIMARY KEY (id_bus, id_servicio)
);

CREATE TABLE piso (
  id_piso         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_de_piso  INT NOT NULL,
  nombre          VARCHAR(30),
  id_bus          INT NOT NULL REFERENCES bus(id_bus),
  esta_habilitado BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_piso_bus ON piso(id_bus);

-- OJO: se eliminó "estado" (DISPONIBLE/RESERVADO). El asiento es físico y
-- pertenece al bus; la disponibilidad depende del VIAJE (ver tabla boleto).
CREATE TABLE asiento (
  id_asiento         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ubicacion          VARCHAR(4) NOT NULL,
  tiene_ventana      BOOLEAN NOT NULL,
  id_piso            INT NOT NULL REFERENCES piso(id_piso),
  id_tipo_de_asiento INT NOT NULL REFERENCES tipo_de_asiento(id_tipo_de_asiento),
  esta_habilitado    BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (id_piso, ubicacion)
);
CREATE INDEX idx_asiento_tipo ON asiento(id_tipo_de_asiento);

-- ---------- RUTAS Y VIAJES ----------
CREATE TABLE terminal (
  id_terminal     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR(100) NOT NULL,
  pais            VARCHAR(60)  NOT NULL,
  ciudad          VARCHAR(60)  NOT NULL,
  direccion       VARCHAR(200) NOT NULL,
  latitud         NUMERIC(9,6),
  longitud        NUMERIC(9,6),
  id_empresa      INT NOT NULL REFERENCES empresa(id_empresa),
  esta_habilitado BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_terminal_empresa ON terminal(id_empresa);

CREATE TABLE ruta (
  id_ruta                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  distancia_de_recorrido NUMERIC(6,2) NOT NULL,
  id_empresa             INT NOT NULL REFERENCES empresa(id_empresa),
  id_terminal_origen     INT NOT NULL REFERENCES terminal(id_terminal),
  id_terminal_destino    INT NOT NULL REFERENCES terminal(id_terminal),
  esta_habilitado        BOOLEAN NOT NULL DEFAULT TRUE,
  CHECK (id_terminal_origen <> id_terminal_destino)
);
CREATE INDEX idx_ruta_origen  ON ruta(id_terminal_origen);
CREATE INDEX idx_ruta_destino ON ruta(id_terminal_destino);

CREATE TABLE viaje (
  id_viaje                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estado                    estado_viaje NOT NULL,
  duracion_estimada_minutos INT NOT NULL DEFAULT 0,
  instante_abordaje         TIMESTAMPTZ NOT NULL,
  instante_partida          TIMESTAMPTZ,
  instante_llegada          TIMESTAMPTZ,
  id_ruta                   INT NOT NULL REFERENCES ruta(id_ruta),
  id_bus                    INT NOT NULL REFERENCES bus(id_bus),
  id_empresa                INT NOT NULL REFERENCES empresa(id_empresa),
  esta_habilitado           BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_viaje_ruta    ON viaje(id_ruta);
CREATE INDEX idx_viaje_bus     ON viaje(id_bus);
CREATE INDEX idx_viaje_empresa ON viaje(id_empresa);

CREATE TABLE tarifa (
  id_tarifa          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  precio             NUMERIC(10,2) NOT NULL,      -- antes FLOAT
  detalle            VARCHAR(100),
  id_viaje           INT NOT NULL REFERENCES viaje(id_viaje),
  id_tipo_de_asiento INT NOT NULL REFERENCES tipo_de_asiento(id_tipo_de_asiento),
  esta_habilitado    BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_tarifa_viaje ON tarifa(id_viaje);
CREATE INDEX idx_tarifa_tipo  ON tarifa(id_tipo_de_asiento);

-- ---------- RESERVAS ----------
CREATE TABLE pago (
  id_pago         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto           NUMERIC(10,2) NOT NULL,
  estado          estado_pago NOT NULL DEFAULT 'PENDIENTE',
  metodo_pago     metodo_pago NOT NULL,
  moneda          VARCHAR(4) NOT NULL,
  esta_habilitado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE reserva (
  id_reserva      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estado          estado_reserva NOT NULL DEFAULT 'PAGO_PENDIENTE',
  expira_en       TIMESTAMPTZ,   -- NUEVO: hold de asientos mientras el pago está pendiente
  id_viajero      INT NOT NULL REFERENCES viajero(id_viajero),
  id_viaje_ida    INT NOT NULL REFERENCES viaje(id_viaje),
  id_viaje_vuelta INT REFERENCES viaje(id_viaje),
  id_pago         INT REFERENCES pago(id_pago),
  esta_habilitado BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_reserva_viajero ON reserva(id_viajero);
CREATE INDEX idx_reserva_ida     ON reserva(id_viaje_ida);
CREATE INDEX idx_reserva_vuelta  ON reserva(id_viaje_vuelta);
CREATE INDEX idx_reserva_pago    ON reserva(id_pago);

-- PASAJERO ahora es solo la persona (datos personales)
CREATE TABLE pasajero (
  id_pasajero        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres            VARCHAR(60) NOT NULL,
  apellidos          VARCHAR(60) NOT NULL,
  tipo_documento     tipo_documento NOT NULL,
  numero_documento   VARCHAR(30) NOT NULL,
  correo_electronico VARCHAR(120),
  telefono           VARCHAR(20),
  id_reserva         INT NOT NULL REFERENCES reserva(id_reserva),
  esta_habilitado    BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_pasajero_reserva ON pasajero(id_reserva);

-- NUEVO: BOLETO = pasajero + viaje + asiento + tarifa.
-- Un viaje de ida y vuelta genera 2 boletos por pasajero.
-- El índice único parcial impide vender el mismo asiento dos veces en un viaje.
CREATE TABLE boleto (
  id_boleto       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pasajero     INT NOT NULL REFERENCES pasajero(id_pasajero),
  id_viaje        INT NOT NULL REFERENCES viaje(id_viaje),
  id_asiento      INT NOT NULL REFERENCES asiento(id_asiento),
  id_tarifa       INT NOT NULL REFERENCES tarifa(id_tarifa),
  esta_habilitado BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uq_boleto_viaje_asiento
  ON boleto(id_viaje, id_asiento) WHERE esta_habilitado;
CREATE INDEX idx_boleto_pasajero ON boleto(id_pasajero);
CREATE INDEX idx_boleto_tarifa   ON boleto(id_tarifa);

-- =====================================================================
-- AUTH: al crearse un usuario en auth.users (email/contraseña o Google)
-- se crea su fila en VIAJERO. Empresas y administradores se crean desde
-- el server con service_role y app_metadata.rol = 'EMPRESA' | 'ADMIN'
-- (el trigger los ignora y el server inserta su fila con id_auth).
-- =====================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF COALESCE(NEW.raw_app_meta_data->>'rol', 'VIAJERO') = 'VIAJERO' THEN
    INSERT INTO public.viajero (id_auth, correo_electronico, nombres, apellidos, avatar_url)
    VALUES (
      NEW.id,
      NEW.email,
      COALESCE(NEW.raw_user_meta_data->>'given_name',
               NEW.raw_user_meta_data->>'nombres',
               split_part(COALESCE(NEW.raw_user_meta_data->>'full_name', ''), ' ', 1),
               ''),
      COALESCE(NEW.raw_user_meta_data->>'family_name',
               NEW.raw_user_meta_data->>'apellidos',
               ''),
      NEW.raw_user_meta_data->>'avatar_url'
    );
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

