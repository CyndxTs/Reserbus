-- Búsqueda de viajes DIRECTOS ofertables entre dos paradas cualesquiera de un mismo viaje:
-- viajes PROGRAMADO o EN_CURSO cuya parada de origen aún no ha salido.
-- Ejemplo: SELECT * FROM v_oferta_directa WHERE id_terminal_origen = 1
--            AND id_terminal_destino = 5 AND salida_utc >= '2026-11-15';
-- Escala (1 transbordo) = unir dos filas: la 1.ª llega al terminal intermedio y la 2.ª
-- sale de ahí con margen:  o1.id_terminal_destino = o2.id_terminal_origen
--   AND o2.salida_utc >= o1.llegada_utc + interval '1 hour'  AND o1.id_viaje <> o2.id_viaje
DROP VIEW IF EXISTS v_oferta_directa CASCADE;
CREATE VIEW v_oferta_directa AS
SELECT a.id_viaje, v.id_empresa, e.razon_social,
       a.id_terminal AS id_terminal_origen,  a.posicion AS posicion_origen,
       b.id_terminal AS id_terminal_destino, b.posicion AS posicion_destino,
       a.salida_estimada_actual  AS salida_utc,
       b.llegada_estimada_actual AS llegada_utc,
       b.llegada_estimada_actual - a.salida_estimada_actual AS duracion,
       v.estado AS estado_viaje
FROM viaje_parada a
JOIN viaje_parada b ON b.id_viaje = a.id_viaje AND b.posicion > a.posicion
JOIN viaje v   ON v.id_viaje = a.id_viaje
JOIN empresa e ON e.id_empresa = v.id_empresa
WHERE v.estado IN ('PROGRAMADO', 'EN_CURSO')
  AND a.estado <> 'CANCELADO' AND b.estado <> 'CANCELADO'
  AND a.salida_estimada_actual > now();
ALTER VIEW v_oferta_directa SET (security_invoker = true);

-- Resumen de reservas para la cuenta del viajero (incluye las canceladas y su reembolso).
DROP VIEW IF EXISTS v_reserva_resumen CASCADE;
CREATE VIEW v_reserva_resumen AS
SELECT r.id_reserva, r.codigo_reserva, r.id_viajero, r.estado, r.expira_en, r.creado_en,
       r.cancelada_en, r.motivo_cancelacion, r.monto_reembolsado,
       COUNT(b.id_boleto)           AS total_boletos,
       COALESCE(SUM(b.precio_total), 0) AS monto_total,
       MIN(vp.salida_estimada_actual)   AS primera_salida_utc
FROM reserva r
LEFT JOIN boleto b ON b.id_reserva = r.id_reserva
LEFT JOIN viaje_parada vp ON vp.id_viaje = b.id_viaje AND vp.posicion = b.posicion_abordaje
GROUP BY r.id_reserva;
ALTER VIEW v_reserva_resumen SET (security_invoker = true);

