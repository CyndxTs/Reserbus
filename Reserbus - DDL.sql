-- Desfase respecto a UTC, con vigencia anual (solo mes/día/hora; se repite cada año).
-- Los límites se expresan en HORA LOCAL del propio desfase de la fila.
-- Intervalo [inicio, fin): puede cruzar fin de año (inicio > fin).
-- Si inicio = fin la fila vale todo el año (países sin horario de verano).
DROP TABLE IF EXISTS desfase_horario CASCADE;
CREATE TABLE desfase_horario (
  id_desfase       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pais          INT NOT NULL REFERENCES pais(id_pais),
  descripcion      VARCHAR(60),
  minutos_desfase  SMALLINT NOT NULL CHECK (minutos_desfase BETWEEN -720 AND 840),  -- Perú = -300
  mes_inicio       SMALLINT NOT NULL CHECK (mes_inicio BETWEEN 1 AND 12),
  dia_inicio       SMALLINT NOT NULL CHECK (dia_inicio BETWEEN 1 AND 31),
  hora_inicio      TIME NOT NULL DEFAULT '00:00',
  mes_fin          SMALLINT NOT NULL CHECK (mes_fin BETWEEN 1 AND 12),
  dia_fin          SMALLINT NOT NULL CHECK (dia_fin BETWEEN 1 AND 31),
  hora_fin         TIME NOT NULL DEFAULT '00:00',
  clave_inicio     INT GENERATED ALWAYS AS (
      mes_inicio * 1000000 + dia_inicio * 10000
      + EXTRACT(HOUR FROM hora_inicio)::int * 60 + EXTRACT(MINUTE FROM hora_inicio)::int) STORED,
  clave_fin        INT GENERATED ALWAYS AS (
      mes_fin * 1000000 + dia_fin * 10000
      + EXTRACT(HOUR FROM hora_fin)::int * 60 + EXTRACT(MINUTE FROM hora_fin)::int) STORED
);
CREATE INDEX idx_desfase_pais ON desfase_horario(id_pais);

-- UTC -> hora local de un país (TIMESTAMP sin zona).
DROP FUNCTION IF EXISTS fn_hora_local(INT, TIMESTAMPTZ) CASCADE;
CREATE FUNCTION fn_hora_local(p_id_pais INT, p_instante TIMESTAMPTZ)
RETURNS TIMESTAMP LANGUAGE sql STABLE AS $$
  SELECT l.hora_local
  FROM desfase_horario d
  CROSS JOIN LATERAL (
    SELECT (p_instante AT TIME ZONE 'UTC') + make_interval(mins => d.minutos_desfase) AS hora_local) l
  CROSS JOIN LATERAL (
    SELECT EXTRACT(MONTH  FROM l.hora_local)::int * 1000000
         + EXTRACT(DAY    FROM l.hora_local)::int * 10000
         + EXTRACT(HOUR   FROM l.hora_local)::int * 60
         + EXTRACT(MINUTE FROM l.hora_local)::int AS clave) k
  WHERE d.id_pais = p_id_pais
    AND CASE WHEN d.clave_inicio = d.clave_fin THEN TRUE
             WHEN d.clave_inicio < d.clave_fin THEN k.clave >= d.clave_inicio AND k.clave < d.clave_fin
             ELSE k.clave >= d.clave_inicio OR k.clave < d.clave_fin END
  LIMIT 1;
$$;

