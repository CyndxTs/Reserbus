-- Una empresa no puede crear un servicio con el mismo nombre que uno general.
DROP FUNCTION IF EXISTS fn_servicio_nombre_unico() CASCADE;
CREATE FUNCTION fn_servicio_nombre_unico() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.id_empresa IS NOT NULL AND EXISTS (
       SELECT 1 FROM servicio s WHERE s.id_empresa IS NULL AND lower(s.nombre) = lower(NEW.nombre)) THEN
    RAISE EXCEPTION 'El servicio "%" ya existe como servicio general', NEW.nombre;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_servicio_nombre_unico
  BEFORE INSERT OR UPDATE OF nombre, id_empresa ON servicio
  FOR EACH ROW EXECUTE FUNCTION fn_servicio_nombre_unico();

