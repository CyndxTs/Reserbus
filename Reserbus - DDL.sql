-- =====================================================================
-- RESERBUS — esquema para Supabase (PostgreSQL)
-- Ejecutar completo en: Supabase Dashboard → SQL Editor
-- Notas:
--  * Tablas en minúsculas (Postgres plega a minúsculas; en los modelos
--    Sequelize cambia tableName: 'VIAJERO' -> 'viajero', etc.)
--  * Las contraseñas NO se guardan aquí: viven en auth.users (Supabase Auth)
--  * RLS activado en todo: el acceso es solo vía Express (rol postgres)
