DROP TABLE IF EXISTS tramo_ruta CASCADE;
CREATE TABLE tramo_ruta (
  id_tramo           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ruta            INT NOT NULL REFERENCES ruta(id_ruta),
  posicion           SMALLINT NOT NULL CHECK (posicion >= 1),          -- 1..n
  id_terminal_inicio INT NOT NULL REFERENCES terminal(id_terminal),
  id_terminal_fin    INT NOT NULL REFERENCES terminal(id_terminal),
  distancia_km       NUMERIC(7,2) NOT NULL CHECK (distancia_km > 0),   -- por carretera
  CHECK (id_terminal_inicio <> id_terminal_fin),
  UNIQUE (id_ruta, posicion),
  UNIQUE (id_tramo, id_ruta)
);
CREATE INDEX idx_tramo_ruta ON tramo_ruta(id_ruta);

-- Los tramos deben ser contiguos: 1..n, el primero parte del origen, cada uno empieza
-- donde terminó el anterior y el último llega al destino. Se valida al COMMIT.
DROP FUNCTION IF EXISTS fn_validar_ruta() CASCADE;
CREATE FUNCTION fn_validar_ruta() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_ruta INT := CASE WHEN TG_OP = 'DELETE' THEN OLD.id_ruta ELSE NEW.id_ruta END;
  v_origen INT; v_destino INT; v_prev INT; v_n INT := 0; r RECORD;
BEGIN
  SELECT id_terminal_origen, id_terminal_destino INTO v_origen, v_destino
  FROM ruta WHERE id_ruta = v_ruta;
  IF NOT FOUND THEN RETURN NULL; END IF;
  v_prev := v_origen;
  FOR r IN SELECT * FROM tramo_ruta WHERE id_ruta = v_ruta ORDER BY posicion LOOP
    v_n := v_n + 1;
    IF r.posicion <> v_n THEN
      RAISE EXCEPTION 'Ruta %: las posiciones de tramo deben ser 1..n sin huecos', v_ruta;
    END IF;
    IF r.id_terminal_inicio <> v_prev THEN
      RAISE EXCEPTION 'Ruta %: el tramo % no empieza donde terminó el anterior', v_ruta, r.posicion;
    END IF;
    v_prev := r.id_terminal_fin;
  END LOOP;
  IF v_n = 0 THEN RAISE EXCEPTION 'Ruta % no tiene tramos', v_ruta; END IF;
  IF v_prev <> v_destino THEN
    RAISE EXCEPTION 'Ruta %: el último tramo no llega al terminal destino', v_ruta;
  END IF;
  RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_validar_ruta
  AFTER INSERT OR UPDATE OR DELETE ON tramo_ruta
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION fn_validar_ruta();

-- =====================================================================
-- 7. PLAN DE VIAJE (= horario) Y FRECUENCIAS
-- =====================================================================
-- Plan: una empresa ofrece una ruta (suya) durante un plazo de vigencia.
-- Para una misma (empresa, ruta) no pueden solaparse planes habilitados.
-- tiempo_parada_horas: espera en CADA terminal intermedio (no el origen ni el destino).
-- Es igual para todas las paradas del plan y sirve también como descanso del chofer:
-- durante la parada el bus y el chofer siguen ocupados (el rango del viaje la incluye).
DROP TABLE IF EXISTS plan_viaje CASCADE;
CREATE TABLE plan_viaje (
  id_plan              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa           INT NOT NULL REFERENCES empresa(id_empresa),
  id_ruta              INT NOT NULL,
  nombre               VARCHAR(100),
  vigencia_inicio      TIMESTAMPTZ NOT NULL,
  vigencia_fin         TIMESTAMPTZ NOT NULL,
  tiempo_parada_horas  NUMERIC(4,2) NOT NULL DEFAULT 0 CHECK (tiempo_parada_horas >= 0),
  esta_habilitado      BOOLEAN NOT NULL DEFAULT TRUE,
  FOREIGN KEY (id_ruta, id_empresa) REFERENCES ruta(id_ruta, id_empresa),   -- la ruta es de la misma empresa
  CHECK (vigencia_inicio < vigencia_fin),
  UNIQUE (id_plan, id_empresa),
  EXCLUDE USING gist (id_empresa WITH =, id_ruta WITH =,
                      tstzrange(vigencia_inicio, vigencia_fin) WITH &&) WHERE (esta_habilitado)
);
CREATE INDEX idx_plan_ruta ON plan_viaje(id_ruta);

-- Frecuencia: día de la semana + hora, AMBOS EN UTC, con bus y chofer asignados.
-- (Un bus o un chofer no pueden tener dos salidas a la misma hora UTC del mismo día;
--  los solapes en el tiempo se controlan en viaje con las exclusiones por bus y chofer.)
DROP TABLE IF EXISTS frecuencia CASCADE;
CREATE TABLE frecuencia (
  id_frecuencia    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_plan          INT NOT NULL,
  id_empresa       INT NOT NULL,
  id_dia           SMALLINT NOT NULL REFERENCES dia_semana(id_dia),
  hora_salida_utc  TIME NOT NULL,
  id_bus           INT NOT NULL,
  id_chofer        INT NOT NULL,
  esta_habilitado  BOOLEAN NOT NULL DEFAULT TRUE,
  -- bus, chofer y plan deben ser de la MISMA empresa
  FOREIGN KEY (id_plan,   id_empresa) REFERENCES plan_viaje(id_plan, id_empresa),
  FOREIGN KEY (id_bus,    id_empresa) REFERENCES bus(id_bus, id_empresa),
  FOREIGN KEY (id_chofer, id_empresa) REFERENCES chofer(id_chofer, id_empresa),
  UNIQUE (id_bus,    id_dia, hora_salida_utc),
  UNIQUE (id_chofer, id_dia, hora_salida_utc),
  UNIQUE (id_frecuencia, id_empresa)
);
CREATE INDEX idx_frecuencia_plan ON frecuencia(id_plan);

-- =====================================================================
-- 8. VIAJES INSTANCIADOS Y SUS PARADAS (instantes)
-- =====================================================================
-- id_tipo_bus: tipo del bus asignado. La FK (id_bus, id_tipo_bus) obliga a que, si se cambia
-- el bus de esta instancia, el nuevo sea del MISMO tipo (misma distribución de asientos).
-- inicio_utc / fin_utc: salida del origen y llegada final con las horas INICIALES; incluyen las
-- paradas. Sobre este rango se prohíben solapes de bus y de chofer (los retrasos no los afectan).
-- El chofer sí puede cambiarse libremente (misma empresa y sin solapes).
DROP TABLE IF EXISTS viaje CASCADE;
CREATE TABLE viaje (
  id_viaje       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_frecuencia  INT NOT NULL,
  id_empresa     INT NOT NULL,
  id_tipo_bus    INT NOT NULL,
  id_bus         INT NOT NULL,
  id_chofer      INT NOT NULL,
  fecha_utc      DATE NOT NULL,      -- fecha UTC de la salida; con la hora de la frecuencia da la salida
  inicio_utc     TIMESTAMPTZ NOT NULL,
  fin_utc        TIMESTAMPTZ NOT NULL,
  estado         estado_viaje NOT NULL DEFAULT 'PROGRAMADO',
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (fin_utc >= inicio_utc),
  FOREIGN KEY (id_frecuencia, id_empresa) REFERENCES frecuencia(id_frecuencia, id_empresa),
  FOREIGN KEY (id_bus,    id_empresa)     REFERENCES bus(id_bus, id_empresa),
  FOREIGN KEY (id_bus,    id_tipo_bus)    REFERENCES bus(id_bus, id_tipo_bus),
  FOREIGN KEY (id_chofer, id_empresa)     REFERENCES chofer(id_chofer, id_empresa),
  UNIQUE (id_frecuencia, fecha_utc),
  UNIQUE (id_viaje, id_tipo_bus),
  CONSTRAINT ex_viaje_bus_sin_solape
    EXCLUDE USING gist (id_bus WITH =, tstzrange(inicio_utc, fin_utc) WITH &&)
    WHERE (estado <> 'CANCELADO'),
  CONSTRAINT ex_viaje_chofer_sin_solape
    EXCLUDE USING gist (id_chofer WITH =, tstzrange(inicio_utc, fin_utc) WITH &&)
    WHERE (estado <> 'CANCELADO')
);
CREATE INDEX idx_viaje_fecha ON viaje(fecha_utc);
CREATE INDEX idx_viaje_bus   ON viaje(id_bus);

-- Una fila por parada del viaje (posición 1 = origen). Es la tabla sobre la que se
-- filtran las búsquedas, incluidas las combinaciones con escala.
-- Primera parada: sin llegada. Última parada: sin salida.
DROP TABLE IF EXISTS viaje_parada CASCADE;
CREATE TABLE viaje_parada (
  id_viaje_parada            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_viaje                   INT NOT NULL REFERENCES viaje(id_viaje) ON DELETE CASCADE,
  posicion                   SMALLINT NOT NULL CHECK (posicion >= 1),
  id_terminal                INT NOT NULL REFERENCES terminal(id_terminal),
  distancia_desde_anterior_km NUMERIC(7,2) CHECK (distancia_desde_anterior_km > 0),   -- copia del tramo
  tiempo_parada_horas        NUMERIC(4,2) NOT NULL DEFAULT 0,                         -- copia del plan
  llegada_estimada_inicial   TIMESTAMPTZ,
  llegada_estimada_actual    TIMESTAMPTZ,
  llegada_real               TIMESTAMPTZ,
  salida_estimada_inicial    TIMESTAMPTZ,
  salida_estimada_actual     TIMESTAMPTZ,
  salida_real                TIMESTAMPTZ,
  estado                     estado_parada NOT NULL DEFAULT 'A_TIEMPO',
  UNIQUE (id_viaje, posicion),
  CHECK ((posicion = 1) = (llegada_estimada_inicial IS NULL)),
  CHECK ((posicion = 1) = (llegada_estimada_actual  IS NULL)),
  CHECK (salida_estimada_inicial IS NULL OR llegada_estimada_inicial IS NULL
         OR salida_estimada_inicial >= llegada_estimada_inicial)
);
CREATE INDEX idx_vp_terminal_salida  ON viaje_parada(id_terminal, salida_estimada_actual);
CREATE INDEX idx_vp_terminal_llegada ON viaje_parada(id_terminal, llegada_estimada_actual);

DROP TABLE IF EXISTS viaje_parada_historial CASCADE;
CREATE TABLE viaje_parada_historial (
  id_historial     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_viaje_parada  INT NOT NULL REFERENCES viaje_parada(id_viaje_parada) ON DELETE CASCADE,
  llegada_anterior TIMESTAMPTZ,
  llegada_nueva    TIMESTAMPTZ,
  salida_anterior  TIMESTAMPTZ,
  salida_nueva     TIMESTAMPTZ,
  estado_anterior  estado_parada NOT NULL,
  estado_nuevo     estado_parada NOT NULL,
  motivo           VARCHAR(200),
  registrado_en    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_vph_parada ON viaje_parada_historial(id_viaje_parada);

-- Al cambiar las horas estimadas "actuales": recalcula el estado (RETRASADO/ADELANTADO/
-- A_TIEMPO respecto a la estimación inicial) y guarda historial. CANCELADO se fija a mano.
-- El motivo se pasa con:  SELECT set_config('reserbus.motivo', 'Tráfico', true);
DROP FUNCTION IF EXISTS fn_viaje_parada_historial() CASCADE;
CREATE FUNCTION fn_viaje_parada_historial() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_delta INTERVAL;
BEGIN
  IF NEW.estado <> 'CANCELADO' THEN
    v_delta := COALESCE(
      NULLIF(NEW.llegada_estimada_actual - NEW.llegada_estimada_inicial, INTERVAL '0'),
      NEW.salida_estimada_actual - NEW.salida_estimada_inicial,
      INTERVAL '0');
    NEW.estado := CASE WHEN v_delta > INTERVAL '0' THEN 'RETRASADO'::estado_parada
                       WHEN v_delta < INTERVAL '0' THEN 'ADELANTADO'::estado_parada
                       ELSE 'A_TIEMPO'::estado_parada END;
  END IF;
  IF NEW.llegada_estimada_actual IS DISTINCT FROM OLD.llegada_estimada_actual
     OR NEW.salida_estimada_actual IS DISTINCT FROM OLD.salida_estimada_actual
     OR NEW.estado IS DISTINCT FROM OLD.estado THEN
    INSERT INTO viaje_parada_historial
      (id_viaje_parada, llegada_anterior, llegada_nueva, salida_anterior, salida_nueva,
       estado_anterior, estado_nuevo, motivo)
    VALUES
      (OLD.id_viaje_parada, OLD.llegada_estimada_actual, NEW.llegada_estimada_actual,
       OLD.salida_estimada_actual, NEW.salida_estimada_actual, OLD.estado, NEW.estado,
       NULLIF(current_setting('reserbus.motivo', true), ''));
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_viaje_parada_historial
  BEFORE UPDATE ON viaje_parada
  FOR EACH ROW EXECUTE FUNCTION fn_viaje_parada_historial();

-- Conflictos detectados al generar viajes en segundo plano (cron): el bus o el chofer ya
-- estaban ocupados esa fecha. Sirven para avisar a la empresa; se limpian solos si luego se genera.
DROP TABLE IF EXISTS generacion_conflicto CASCADE;
CREATE TABLE generacion_conflicto (
  id_conflicto  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_frecuencia INT NOT NULL REFERENCES frecuencia(id_frecuencia) ON DELETE CASCADE,
  fecha_utc     DATE NOT NULL,
  restriccion   VARCHAR(80),
  creado_en     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id_frecuencia, fecha_utc)
);

-- ---------- Instanciación automática y cálculo de estimados ----------
-- Cada tramo: llegada = salida anterior + distancia / velocidad del bus;
--             salida  = llegada + tiempo de parada del plan (salvo en el destino final).
-- El viaje se inserta con fin = inicio (rango vacío) y al final se actualiza fin_utc: ahí las
-- exclusiones por bus y chofer validan que no haya solapes con otros viajes.
DROP FUNCTION IF EXISTS sp_instanciar_viaje(INT, DATE) CASCADE;
CREATE FUNCTION sp_instanciar_viaje(p_id_frecuencia INT, p_fecha_utc DATE)
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE
  f frecuencia%ROWTYPE; pl plan_viaje%ROWTYPE; bu bus%ROWTYPE; ch chofer%ROWTYPE;
  v_viaje INT; v_inicio TIMESTAMPTZ; v_salida TIMESTAMPTZ; v_llegada TIMESTAMPTZ;
  v_max INT; v_term INT; t RECORD;
BEGIN
  SELECT * INTO f FROM frecuencia WHERE id_frecuencia = p_id_frecuencia;
  IF NOT FOUND THEN RAISE EXCEPTION 'Frecuencia % no existe', p_id_frecuencia; END IF;
  IF EXTRACT(ISODOW FROM p_fecha_utc)::int <> f.id_dia THEN
    RAISE EXCEPTION 'La fecha % no corresponde al día % de la frecuencia', p_fecha_utc, f.id_dia;
  END IF;
  SELECT * INTO pl FROM plan_viaje WHERE id_plan = f.id_plan;
  SELECT * INTO bu FROM bus    WHERE id_bus    = f.id_bus;
  SELECT * INTO ch FROM chofer WHERE id_chofer = f.id_chofer;
  IF NOT bu.esta_habilitado THEN RAISE EXCEPTION 'El bus % está deshabilitado', bu.placa; END IF;
  IF NOT ch.esta_habilitado THEN RAISE EXCEPTION 'El chofer % % está deshabilitado', ch.nombres, ch.apellidos; END IF;

  v_inicio := (p_fecha_utc + f.hora_salida_utc) AT TIME ZONE 'UTC';
  IF v_inicio < pl.vigencia_inicio OR v_inicio >= pl.vigencia_fin THEN
    RAISE EXCEPTION 'La salida % está fuera de la vigencia del plan %', v_inicio, pl.id_plan;
  END IF;
  SELECT max(posicion) INTO v_max FROM tramo_ruta WHERE id_ruta = pl.id_ruta;

  INSERT INTO viaje (id_frecuencia, id_empresa, id_tipo_bus, id_bus, id_chofer, fecha_utc, inicio_utc, fin_utc)
  VALUES (f.id_frecuencia, f.id_empresa, bu.id_tipo_bus, f.id_bus, f.id_chofer, p_fecha_utc, v_inicio, v_inicio)
  RETURNING id_viaje INTO v_viaje;

  SELECT id_terminal_inicio INTO v_term FROM tramo_ruta WHERE id_ruta = pl.id_ruta AND posicion = 1;
  v_salida := v_inicio;
  INSERT INTO viaje_parada (id_viaje, posicion, id_terminal, tiempo_parada_horas,
                            salida_estimada_inicial, salida_estimada_actual)
  VALUES (v_viaje, 1, v_term, 0, v_salida, v_salida);

  FOR t IN SELECT * FROM tramo_ruta WHERE id_ruta = pl.id_ruta ORDER BY posicion LOOP
    v_llegada := date_trunc('minute', v_salida + (t.distancia_km / bu.velocidad_promedio_kmh)::float8 * INTERVAL '1 hour');
    IF t.posicion = v_max THEN
      INSERT INTO viaje_parada (id_viaje, posicion, id_terminal, distancia_desde_anterior_km,
                                tiempo_parada_horas, llegada_estimada_inicial, llegada_estimada_actual)
      VALUES (v_viaje, t.posicion + 1, t.id_terminal_fin, t.distancia_km, 0, v_llegada, v_llegada);
    ELSE
      v_salida := v_llegada + pl.tiempo_parada_horas::float8 * INTERVAL '1 hour';
      INSERT INTO viaje_parada (id_viaje, posicion, id_terminal, distancia_desde_anterior_km,
                                tiempo_parada_horas, llegada_estimada_inicial, llegada_estimada_actual,
                                salida_estimada_inicial, salida_estimada_actual)
      VALUES (v_viaje, t.posicion + 1, t.id_terminal_fin, t.distancia_km, pl.tiempo_parada_horas,
              v_llegada, v_llegada, v_salida, v_salida);
    END IF;
  END LOOP;

  UPDATE viaje SET fin_utc = v_llegada WHERE id_viaje = v_viaje;   -- aquí se validan los solapes
  RETURN v_viaje;
END $$;

-- Genera los viajes de las frecuencias habilitadas entre dos fechas UTC (respetando la vigencia
-- del plan). Idempotente: se puede correr a diario sin duplicar.
--   p_id_frecuencia: NULL = todas.
--   p_estricto: TRUE = si el bus/chofer está ocupado, lanza error (se usa al crear la frecuencia);
--               FALSE = registra el conflicto en generacion_conflicto y sigue (cron).
--   p_solo_futuros: TRUE = ignora salidas que ya pasaron (poner FALSE para cargar datos históricos).
DROP FUNCTION IF EXISTS sp_generar_viajes(DATE, DATE, INT, BOOLEAN, BOOLEAN) CASCADE;
CREATE FUNCTION sp_generar_viajes(p_desde DATE, p_hasta DATE, p_id_frecuencia INT DEFAULT NULL,
                                  p_estricto BOOLEAN DEFAULT FALSE, p_solo_futuros BOOLEAN DEFAULT TRUE)
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE f RECORD; d DATE; v_salida TIMESTAMPTZ; n INT := 0; v_c TEXT; v_msg TEXT;
BEGIN
  FOR f IN
    SELECT fr.*, pl.vigencia_inicio, pl.vigencia_fin
    FROM frecuencia fr JOIN plan_viaje pl ON pl.id_plan = fr.id_plan
    WHERE fr.esta_habilitado AND pl.esta_habilitado
      AND (p_id_frecuencia IS NULL OR fr.id_frecuencia = p_id_frecuencia)
  LOOP
    FOR d IN SELECT g::date FROM generate_series(p_desde::timestamp, p_hasta::timestamp, INTERVAL '1 day') g
             WHERE EXTRACT(ISODOW FROM g)::int = f.id_dia
    LOOP
      v_salida := (d + f.hora_salida_utc) AT TIME ZONE 'UTC';
      CONTINUE WHEN v_salida < f.vigencia_inicio OR v_salida >= f.vigencia_fin;
      CONTINUE WHEN p_solo_futuros AND v_salida <= now();
      CONTINUE WHEN EXISTS (SELECT 1 FROM viaje v WHERE v.id_frecuencia = f.id_frecuencia AND v.fecha_utc = d);
      BEGIN
        PERFORM sp_instanciar_viaje(f.id_frecuencia, d);
        n := n + 1;
        DELETE FROM generacion_conflicto WHERE id_frecuencia = f.id_frecuencia AND fecha_utc = d;
      EXCEPTION WHEN exclusion_violation THEN
        GET STACKED DIAGNOSTICS v_c = CONSTRAINT_NAME;
        IF p_estricto THEN
          v_msg := CASE WHEN v_c = 'ex_viaje_chofer_sin_solape'
                        THEN 'El chofer no está disponible el ' || d || ' (se solapa con otro viaje)'
                        ELSE 'El bus no está disponible el ' || d || ' (se solapa con otro viaje)' END;
          RAISE EXCEPTION '%', v_msg USING ERRCODE = 'exclusion_violation';
        END IF;
        INSERT INTO generacion_conflicto (id_frecuencia, fecha_utc, restriccion)
        VALUES (f.id_frecuencia, d, v_c)
        ON CONFLICT (id_frecuencia, fecha_utc) DO UPDATE SET restriccion = EXCLUDED.restriccion, creado_en = now();
      END;
    END LOOP;
  END LOOP;
  RETURN n;
END $$;

-- Al crear una frecuencia se generan sus viajes dentro del horizonte (fn_param_horizonte_dias).
-- Si el bus o el chofer no están libres, la creación de la frecuencia falla con un mensaje claro.
-- Para cargas masivas (DML) se puede desactivar dentro de la transacción:
--   SELECT set_config('reserbus.generar_auto', 'off', true);
DROP FUNCTION IF EXISTS fn_frecuencia_generar_viajes() CASCADE;
CREATE FUNCTION fn_frecuencia_generar_viajes() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_hoy DATE := (now() AT TIME ZONE 'UTC')::date;
BEGIN
  IF NEW.esta_habilitado AND COALESCE(current_setting('reserbus.generar_auto', true), 'on') <> 'off' THEN
    PERFORM sp_generar_viajes(v_hoy, v_hoy + fn_param_horizonte_dias(), NEW.id_frecuencia, TRUE, TRUE);
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_frecuencia_generar
  AFTER INSERT ON frecuencia
  FOR EACH ROW EXECUTE FUNCTION fn_frecuencia_generar_viajes();

-- Extiende el horizonte de todas las frecuencias (job diario).
DROP FUNCTION IF EXISTS fn_extender_horizonte() CASCADE;
CREATE FUNCTION fn_extender_horizonte() RETURNS INT LANGUAGE plpgsql AS $$
DECLARE v_hoy DATE := (now() AT TIME ZONE 'UTC')::date;
BEGIN
  RETURN sp_generar_viajes(v_hoy, v_hoy + fn_param_horizonte_dias(), NULL, FALSE, TRUE);
END $$;

-- Ocupación de un bus y/o un chofer en una ventana de tiempo (para pintar el calendario del panel).
DROP FUNCTION IF EXISTS fn_ocupacion(INT, INT, TIMESTAMPTZ, TIMESTAMPTZ) CASCADE;
CREATE FUNCTION fn_ocupacion(p_id_bus INT, p_id_chofer INT, p_desde TIMESTAMPTZ, p_hasta TIMESTAMPTZ)
RETURNS TABLE (id_viaje INT, inicio_utc TIMESTAMPTZ, fin_utc TIMESTAMPTZ, estado estado_viaje,
               ocupa_bus BOOLEAN, ocupa_chofer BOOLEAN)
LANGUAGE sql STABLE AS $$
  SELECT v.id_viaje, v.inicio_utc, v.fin_utc, v.estado,
         COALESCE(v.id_bus = p_id_bus, FALSE), COALESCE(v.id_chofer = p_id_chofer, FALSE)
  FROM viaje v
  WHERE v.estado <> 'CANCELADO'
    AND (v.id_bus = p_id_bus OR v.id_chofer = p_id_chofer)
    AND tstzrange(v.inicio_utc, v.fin_utc) && tstzrange(p_desde, p_hasta)
  ORDER BY v.inicio_utc;
$$;

-- =====================================================================
-- 9. RESERVAS, PASAJEROS, PAGOS Y BOLETOS
-- =====================================================================
-- La reserva se crea al pulsar "Continuar" (después de elegir asientos y llenar pasajeros).
-- Desde ese momento corre el hold: expira_en = ahora + fn_param_hold_minutos() (10 min).
DROP TABLE IF EXISTS reserva CASCADE;
CREATE TABLE reserva (
  id_reserva        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_reserva    VARCHAR(8) NOT NULL UNIQUE
                    DEFAULT upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8)),  -- tipo PNR
  id_viajero        INT NOT NULL REFERENCES viajero(id_viajero),
  estado            estado_reserva NOT NULL DEFAULT 'PAGO_PENDIENTE',
  expira_en         TIMESTAMPTZ DEFAULT now() + make_interval(mins => fn_param_hold_minutos()),
  contacto_correo   VARCHAR(120),
  contacto_telefono VARCHAR(20),
  creado_en         TIMESTAMPTZ NOT NULL DEFAULT now(),
  cancelada_en      TIMESTAMPTZ,
  motivo_cancelacion VARCHAR(200),
  monto_reembolsado NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (monto_reembolsado >= 0)
);
CREATE INDEX idx_reserva_viajero ON reserva(id_viajero);
CREATE INDEX idx_reserva_expira  ON reserva(expira_en) WHERE estado = 'PAGO_PENDIENTE';

-- Personas reales que viajan. Registrados (id_viajero) o externos (datos manuales).
DROP TABLE IF EXISTS pasajero CASCADE;
CREATE TABLE pasajero (
  id_pasajero        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva         INT NOT NULL REFERENCES reserva(id_reserva) ON DELETE CASCADE,
  id_viajero         INT REFERENCES viajero(id_viajero),     -- NULL = no registrado
  es_registrado      BOOLEAN GENERATED ALWAYS AS (id_viajero IS NOT NULL) STORED,
  tipo_documento     tipo_documento NOT NULL,
  numero_documento   VARCHAR(30) NOT NULL,
  nombres            VARCHAR(60) NOT NULL,
  apellidos          VARCHAR(60) NOT NULL,
  fecha_nacimiento   DATE,
  correo_electronico VARCHAR(120),
  telefono           VARCHAR(20),
  UNIQUE (id_reserva, tipo_documento, numero_documento),
  UNIQUE (id_pasajero, id_reserva)
);
CREATE INDEX idx_pasajero_reserva ON pasajero(id_reserva);
CREATE INDEX idx_pasajero_viajero ON pasajero(id_viajero);

DROP TABLE IF EXISTS pago CASCADE;
CREATE TABLE pago (
  id_pago            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva         INT NOT NULL REFERENCES reserva(id_reserva),
  monto              NUMERIC(10,2) NOT NULL CHECK (monto >= 0),
  moneda             CHAR(3) NOT NULL DEFAULT 'PEN',
  metodo_pago        metodo_pago NOT NULL,
  estado             estado_pago NOT NULL DEFAULT 'PENDIENTE',
  codigo_transaccion VARCHAR(60),
  pagado_en          TIMESTAMPTZ,
  creado_en          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_pago_reserva ON pago(id_reserva);

-- Cuando un pago queda PAGADO: la reserva pasa a PAGADA y deja de tener hold.
-- Si la reserva ya expiró o fue cancelada, el pago se rechaza (se revierte).
DROP FUNCTION IF EXISTS fn_pago_sincroniza_reserva() CASCADE;
CREATE FUNCTION fn_pago_sincroniza_reserva() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE rv reserva%ROWTYPE;
BEGIN
  IF NEW.estado = 'PAGADO' AND (TG_OP = 'INSERT' OR OLD.estado IS DISTINCT FROM 'PAGADO') THEN
    SELECT * INTO rv FROM reserva WHERE id_reserva = NEW.id_reserva FOR UPDATE;
    IF rv.estado <> 'PAGO_PENDIENTE' THEN
      RAISE EXCEPTION 'La reserva % está % y no admite pagos', rv.codigo_reserva, rv.estado;
    END IF;
    IF rv.expira_en IS NOT NULL AND rv.expira_en <= now() THEN
      RAISE EXCEPTION 'La reserva % expiró; los asientos ya no están retenidos', rv.codigo_reserva;
    END IF;
    UPDATE reserva SET estado = 'PAGADA', expira_en = NULL WHERE id_reserva = NEW.id_reserva;
  END IF;
  RETURN NULL;
END $$;

CREATE TRIGGER trg_pago_sincroniza_reserva
  AFTER INSERT OR UPDATE OF estado ON pago
  FOR EACH ROW EXECUTE FUNCTION fn_pago_sincroniza_reserva();

-- BOLETO = un pasajero ocupa un asiento en un viaje entre dos paradas.
-- Una reserva con escala tiene boletos en 2+ viajes (orden_trayecto 1, 2...).
-- La exclusión impide vender el mismo asiento en tramos que se solapan, pero permite
-- reutilizarlo cuando uno baja donde otro sube (rangos [abordaje, descenso)).
-- El asiento se valida contra el TIPO de bus del viaje (no contra el bus), así un cambio de bus
-- del mismo tipo no afecta a los boletos vendidos.
DROP TABLE IF EXISTS boleto CASCADE;
CREATE TABLE boleto (
  id_boleto          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva         INT NOT NULL,
  id_pasajero        INT NOT NULL,
  id_viaje           INT NOT NULL,
  id_tipo_bus        INT NOT NULL,
  id_asiento         INT NOT NULL,
  posicion_abordaje  SMALLINT NOT NULL,
  posicion_descenso  SMALLINT NOT NULL,
  orden_trayecto     SMALLINT NOT NULL DEFAULT 1 CHECK (orden_trayecto >= 1),
  sentido            sentido_trayecto NOT NULL DEFAULT 'IDA',
  precio_base        NUMERIC(10,2) NOT NULL CHECK (precio_base >= 0),
  precio_adicional   NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (precio_adicional >= 0),
  precio_total       NUMERIC(10,2) GENERATED ALWAYS AS (precio_base + precio_adicional) STORED,
  estado             estado_boleto NOT NULL DEFAULT 'ACTIVO',
  cancelado_en       TIMESTAMPTZ,
  monto_reembolso    NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (monto_reembolso >= 0),
  asistio            BOOLEAN,                  -- NULL hasta que el viaje termina
  CHECK (posicion_abordaje < posicion_descenso),
  FOREIGN KEY (id_pasajero, id_reserva)             REFERENCES pasajero(id_pasajero, id_reserva),
  FOREIGN KEY (id_viaje, id_tipo_bus)               REFERENCES viaje(id_viaje, id_tipo_bus),
  FOREIGN KEY (id_asiento, id_tipo_bus)             REFERENCES asiento(id_asiento, id_tipo_bus),
  FOREIGN KEY (id_viaje, posicion_abordaje)         REFERENCES viaje_parada(id_viaje, posicion),
  FOREIGN KEY (id_viaje, posicion_descenso)         REFERENCES viaje_parada(id_viaje, posicion),
  EXCLUDE USING gist (id_viaje WITH =, id_asiento WITH =,
                      int4range(posicion_abordaje, posicion_descenso) WITH &&) WHERE (estado = 'ACTIVO')
);
CREATE INDEX idx_boleto_reserva  ON boleto(id_reserva);
CREATE INDEX idx_boleto_pasajero ON boleto(id_pasajero);
CREATE INDEX idx_boleto_viaje    ON boleto(id_viaje);

-- ---------- Hold: expiración de reservas con pago pendiente ----------
-- Pasa a EXPIRADA las reservas vencidas y cancela sus boletos (la exclusión libera los asientos).
-- pg_cron la corre cada minuto; además fn_crear_boleto la invoca antes de vender, para que un
-- asiento vencido no quede bloqueado hasta la siguiente corrida.
DROP FUNCTION IF EXISTS fn_expirar_reservas() CASCADE;
CREATE FUNCTION fn_expirar_reservas() RETURNS INT LANGUAGE plpgsql AS $$
DECLARE rv RECORD; n INT := 0;
BEGIN
  FOR rv IN
    SELECT id_reserva FROM reserva
    WHERE estado = 'PAGO_PENDIENTE' AND expira_en IS NOT NULL AND expira_en <= now()
    FOR UPDATE SKIP LOCKED
  LOOP
    UPDATE boleto SET estado = 'CANCELADO', cancelado_en = now()
     WHERE id_reserva = rv.id_reserva AND estado = 'ACTIVO';
    UPDATE reserva SET estado = 'EXPIRADA' WHERE id_reserva = rv.id_reserva;
    n := n + 1;
  END LOOP;
  RETURN n;
END $$;

-- ---------- Precio, distancia y disponibilidad ----------
DROP FUNCTION IF EXISTS fn_distancia_entre_paradas(INT, INT, INT) CASCADE;
CREATE FUNCTION fn_distancia_entre_paradas(p_id_viaje INT, p_pos_a INT, p_pos_b INT)
RETURNS NUMERIC LANGUAGE sql STABLE AS $$
  SELECT COALESCE(SUM(distancia_desde_anterior_km), 0)
  FROM viaje_parada WHERE id_viaje = p_id_viaje AND posicion > p_pos_a AND posicion <= p_pos_b;
$$;

-- precio_base = km * tarifa por km de la zona (redondeado a soles enteros);
-- precio_adicional = tarifa agregada del tipo de asiento dentro de esa zona.
DROP FUNCTION IF EXISTS fn_precio_boleto(INT, NUMERIC) CASCADE;
CREATE FUNCTION fn_precio_boleto(p_id_asiento INT, p_distancia_km NUMERIC)
RETURNS TABLE (precio_base NUMERIC, precio_adicional NUMERIC) LANGUAGE sql STABLE AS $$
  SELECT ROUND(p_distancia_km * z.tarifa_base_por_km), zt.tarifa_adicional
  FROM asiento a
  JOIN zona z ON z.id_zona = a.id_zona
  JOIN zona_tipo_asiento zt ON zt.id_zona = a.id_zona AND zt.id_tipo_asiento = a.id_tipo_asiento
  WHERE a.id_asiento = p_id_asiento;
$$;

-- Crea un boleto dentro de una reserva con pago pendiente (el hold ya está corriendo).
DROP FUNCTION IF EXISTS fn_crear_boleto(INT, INT, INT, INT, INT, VARCHAR, INT, sentido_trayecto) CASCADE;
CREATE FUNCTION fn_crear_boleto(
  p_id_reserva INT, p_id_pasajero INT, p_id_viaje INT,
  p_pos_abordaje INT, p_pos_descenso INT, p_codigo_asiento VARCHAR,
  p_orden INT DEFAULT 1, p_sentido sentido_trayecto DEFAULT 'IDA')
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE
  v_est_reserva estado_reserva; v_tipo INT; v_est_viaje estado_viaje; v_salida TIMESTAMPTZ;
  v_asiento INT; v_dist NUMERIC; v_base NUMERIC; v_adic NUMERIC; v_id INT;
BEGIN
  PERFORM fn_expirar_reservas();   -- libera holds vencidos antes de intentar vender

  SELECT estado INTO v_est_reserva FROM reserva WHERE id_reserva = p_id_reserva;
  IF NOT FOUND THEN RAISE EXCEPTION 'Reserva % no existe', p_id_reserva; END IF;
  IF v_est_reserva <> 'PAGO_PENDIENTE' THEN
    RAISE EXCEPTION 'La reserva % está % y no admite nuevos boletos', p_id_reserva, v_est_reserva;
  END IF;

  SELECT id_tipo_bus, estado INTO v_tipo, v_est_viaje FROM viaje WHERE id_viaje = p_id_viaje;
  IF NOT FOUND THEN RAISE EXCEPTION 'Viaje % no existe', p_id_viaje; END IF;
  IF v_est_viaje NOT IN ('PROGRAMADO', 'EN_CURSO') THEN
    RAISE EXCEPTION 'El viaje % está % y no admite ventas', p_id_viaje, v_est_viaje;
  END IF;

  SELECT salida_estimada_actual INTO v_salida FROM viaje_parada
   WHERE id_viaje = p_id_viaje AND posicion = p_pos_abordaje;
  IF NOT FOUND THEN RAISE EXCEPTION 'La parada de abordaje % no existe en el viaje %', p_pos_abordaje, p_id_viaje; END IF;
  IF v_salida <= now() THEN RAISE EXCEPTION 'El bus ya salió de la parada de abordaje'; END IF;

  SELECT id_asiento INTO v_asiento FROM asiento
   WHERE id_tipo_bus = v_tipo AND codigo = p_codigo_asiento AND esta_habilitado;
  IF NOT FOUND THEN RAISE EXCEPTION 'El asiento % no existe en el bus del viaje %', p_codigo_asiento, p_id_viaje; END IF;

  v_dist := fn_distancia_entre_paradas(p_id_viaje, p_pos_abordaje, p_pos_descenso);
  SELECT precio_base, precio_adicional INTO v_base, v_adic FROM fn_precio_boleto(v_asiento, v_dist);
  INSERT INTO boleto (id_reserva, id_pasajero, id_viaje, id_tipo_bus, id_asiento, posicion_abordaje,
                      posicion_descenso, orden_trayecto, sentido, precio_base, precio_adicional)
  VALUES (p_id_reserva, p_id_pasajero, p_id_viaje, v_tipo, v_asiento, p_pos_abordaje,
          p_pos_descenso, p_orden, p_sentido, v_base, v_adic)
  RETURNING id_boleto INTO v_id;
  RETURN v_id;
END $$;

-- Mapa de asientos libres para el tramo [pos_a, pos_b] de un viaje (con precio).
-- Los holds vencidos (reserva PAGO_PENDIENTE con expira_en pasado) se consideran libres.
DROP FUNCTION IF EXISTS fn_asientos_disponibles(INT, INT, INT) CASCADE;
CREATE FUNCTION fn_asientos_disponibles(p_id_viaje INT, p_pos_a INT, p_pos_b INT)
RETURNS TABLE (id_asiento INT, codigo VARCHAR, zona VARCHAR, tiene_ventana BOOLEAN,
               fila_mapa SMALLINT, columna_mapa SMALLINT, precio_total NUMERIC)
LANGUAGE sql STABLE AS $$
  WITH d AS (SELECT fn_distancia_entre_paradas(p_id_viaje, p_pos_a, p_pos_b) AS km)
  SELECT a.id_asiento, a.codigo, z.nombre, a.tiene_ventana, a.fila_mapa, a.columna_mapa,
         p.precio_base + p.precio_adicional
  FROM viaje v
  JOIN asiento a ON a.id_tipo_bus = v.id_tipo_bus AND a.esta_habilitado
  JOIN zona z ON z.id_zona = a.id_zona
  CROSS JOIN d
  CROSS JOIN LATERAL fn_precio_boleto(a.id_asiento, d.km) p
  WHERE v.id_viaje = p_id_viaje
    AND NOT EXISTS (
      SELECT 1 FROM boleto b JOIN reserva r ON r.id_reserva = b.id_reserva
      WHERE b.id_viaje = v.id_viaje AND b.id_asiento = a.id_asiento AND b.estado = 'ACTIVO'
        AND int4range(b.posicion_abordaje, b.posicion_descenso) && int4range(p_pos_a, p_pos_b)
        AND NOT (r.estado = 'PAGO_PENDIENTE' AND r.expira_en <= now()))
  ORDER BY a.codigo;
$$;

-- ---------- Cancelación y reembolsos ----------
-- % de reembolso según las horas que faltan para la salida: se aplica la fila con el
-- mayor horas_antes_salida que se cumpla (ej. 48 h -> 90 %, 0 h -> 0 %).
-- Lo usa fn_porcentaje_reembolso.
DROP TABLE IF EXISTS politica_cancelacion CASCADE;
CREATE TABLE politica_cancelacion (
  id_politica          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa           INT NOT NULL REFERENCES empresa(id_empresa),
  horas_antes_salida   INT NOT NULL CHECK (horas_antes_salida >= 0),
  porcentaje_reembolso SMALLINT NOT NULL CHECK (porcentaje_reembolso BETWEEN 0 AND 100),
  UNIQUE (id_empresa, horas_antes_salida)
);

-- % de reembolso de una empresa según las horas que faltan para la salida (0 si no hay fila aplicable).
DROP FUNCTION IF EXISTS fn_porcentaje_reembolso(INT, NUMERIC) CASCADE;
CREATE FUNCTION fn_porcentaje_reembolso(p_id_empresa INT, p_horas NUMERIC)
RETURNS NUMERIC LANGUAGE sql STABLE AS $$
  SELECT COALESCE((SELECT porcentaje_reembolso FROM politica_cancelacion
                    WHERE id_empresa = p_id_empresa AND horas_antes_salida <= p_horas
                    ORDER BY horas_antes_salida DESC LIMIT 1), 0);
$$;

-- El viajero cancela TODA su reserva: boletos CANCELADO (liberan los asientos), reserva CANCELADA
-- y reembolso calculado POR BOLETO con la política de la empresa de cada viaje y las horas que
-- faltan para la salida desde su parada de abordaje. Devuelve el total reembolsado.
-- Solo se puede cancelar si ninguna salida de abordaje ha ocurrido ya.
-- p_id_viajero (opcional) valida que la reserva sea de quien cancela.
DROP FUNCTION IF EXISTS fn_cancelar_reserva(INT, VARCHAR, INT) CASCADE;
CREATE FUNCTION fn_cancelar_reserva(p_id_reserva INT, p_motivo VARCHAR DEFAULT NULL, p_id_viajero INT DEFAULT NULL)
RETURNS NUMERIC LANGUAGE plpgsql AS $$
DECLARE
  rv reserva%ROWTYPE; rec RECORD; v_horas NUMERIC; v_reemb NUMERIC; v_total NUMERIC := 0;
BEGIN
  SELECT * INTO rv FROM reserva WHERE id_reserva = p_id_reserva FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Reserva % no existe', p_id_reserva; END IF;
  IF p_id_viajero IS NOT NULL AND rv.id_viajero <> p_id_viajero THEN
    RAISE EXCEPTION 'La reserva % no pertenece al viajero %', p_id_reserva, p_id_viajero;
  END IF;
  IF rv.estado NOT IN ('PAGO_PENDIENTE', 'PAGADA') THEN
    RAISE EXCEPTION 'No se puede cancelar una reserva en estado %', rv.estado;
  END IF;
  IF EXISTS (SELECT 1 FROM boleto bo
             JOIN viaje_parada vp ON vp.id_viaje = bo.id_viaje AND vp.posicion = bo.posicion_abordaje
             WHERE bo.id_reserva = p_id_reserva AND bo.estado = 'ACTIVO'
               AND vp.salida_estimada_actual <= now()) THEN
    RAISE EXCEPTION 'La reserva % no se puede cancelar: uno de sus viajes ya inició', p_id_reserva;
  END IF;

  FOR rec IN
    SELECT bo.id_boleto, bo.precio_total, v.id_empresa, vp.salida_estimada_actual AS salida
    FROM boleto bo
    JOIN viaje v ON v.id_viaje = bo.id_viaje
    JOIN viaje_parada vp ON vp.id_viaje = bo.id_viaje AND vp.posicion = bo.posicion_abordaje
    WHERE bo.id_reserva = p_id_reserva AND bo.estado = 'ACTIVO'
  LOOP
    v_reemb := 0;
    IF rv.estado = 'PAGADA' THEN
      v_horas := EXTRACT(EPOCH FROM (rec.salida - now())) / 3600;
      v_reemb := ROUND(rec.precio_total * fn_porcentaje_reembolso(rec.id_empresa, v_horas) / 100, 2);
    END IF;
    UPDATE boleto SET estado = 'CANCELADO', cancelado_en = now(), monto_reembolso = v_reemb
     WHERE id_boleto = rec.id_boleto;
    v_total := v_total + v_reemb;
  END LOOP;

  UPDATE reserva SET estado = 'CANCELADA', expira_en = NULL, cancelada_en = now(),
         motivo_cancelacion = p_motivo, monto_reembolsado = v_total
   WHERE id_reserva = p_id_reserva;
  IF v_total > 0 THEN   -- total o parcial; el monto exacto queda en reserva.monto_reembolsado
    UPDATE pago SET estado = 'REEMBOLSADO' WHERE id_reserva = p_id_reserva AND estado = 'PAGADO';
  END IF;
  RETURN v_total;
END $$;

-- La EMPRESA cancela un viaje: viaje y paradas CANCELADO (libera bus y chofer), boletos
-- CANCELADO con reembolso del 100 % si la reserva estaba pagada. Si la reserva se queda sin
-- boletos activos pasa a CANCELADA; si aún tiene boletos en otro viaje, sigue vigente.
-- Devuelve una fila por reserva afectada para que el backend envíe el correo.
DROP FUNCTION IF EXISTS fn_cancelar_viaje(INT, VARCHAR) CASCADE;
CREATE FUNCTION fn_cancelar_viaje(p_id_viaje INT, p_motivo VARCHAR DEFAULT NULL)
RETURNS TABLE (r_id_reserva INT, r_codigo_reserva VARCHAR, r_correo VARCHAR, r_monto_reembolso NUMERIC)
LANGUAGE plpgsql AS $$
DECLARE
  v_estado estado_viaje; v_motivo VARCHAR := COALESCE(p_motivo, 'Viaje cancelado por la empresa');
  rv RECORD; rr RECORD; v_monto NUMERIC; v_quedan INT;
BEGIN
  SELECT estado INTO v_estado FROM viaje WHERE id_viaje = p_id_viaje FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Viaje % no existe', p_id_viaje; END IF;
  IF v_estado IN ('FINALIZADO', 'CANCELADO') THEN
    RAISE EXCEPTION 'El viaje % ya está %', p_id_viaje, v_estado;
  END IF;

  PERFORM set_config('reserbus.motivo', v_motivo, true);
  UPDATE viaje SET estado = 'CANCELADO' WHERE id_viaje = p_id_viaje;
  UPDATE viaje_parada SET estado = 'CANCELADO' WHERE id_viaje = p_id_viaje;

  FOR rv IN SELECT DISTINCT bo.id_reserva FROM boleto bo
            WHERE bo.id_viaje = p_id_viaje AND bo.estado = 'ACTIVO' LOOP
    SELECT r.estado AS estado_reserva, r.codigo_reserva,
           COALESCE(r.contacto_correo, vj.correo_electronico) AS correo
      INTO rr
      FROM reserva r JOIN viajero vj ON vj.id_viajero = r.id_viajero
     WHERE r.id_reserva = rv.id_reserva FOR UPDATE OF r;

    WITH u AS (
      UPDATE boleto SET estado = 'CANCELADO', cancelado_en = now(),
             monto_reembolso = CASE WHEN rr.estado_reserva = 'PAGADA' THEN precio_total ELSE 0 END
       WHERE id_viaje = p_id_viaje AND id_reserva = rv.id_reserva AND estado = 'ACTIVO'
      RETURNING monto_reembolso)
    SELECT COALESCE(SUM(monto_reembolso), 0) INTO v_monto FROM u;

    SELECT count(*) INTO v_quedan FROM boleto WHERE id_reserva = rv.id_reserva AND estado = 'ACTIVO';
    UPDATE reserva SET
           monto_reembolsado  = monto_reembolsado + v_monto,
           estado             = CASE WHEN v_quedan = 0 THEN 'CANCELADA' ELSE estado END,
           cancelada_en       = CASE WHEN v_quedan = 0 THEN now() ELSE cancelada_en END,
           motivo_cancelacion = CASE WHEN v_quedan = 0 THEN v_motivo ELSE motivo_cancelacion END,
           expira_en          = CASE WHEN v_quedan = 0 THEN NULL ELSE expira_en END
     WHERE id_reserva = rv.id_reserva;
    IF v_quedan = 0 AND v_monto > 0 THEN
      UPDATE pago SET estado = 'REEMBOLSADO' WHERE id_reserva = rv.id_reserva AND estado = 'PAGADO';
    END IF;

    r_id_reserva := rv.id_reserva; r_codigo_reserva := rr.codigo_reserva;
    r_correo := rr.correo;         r_monto_reembolso := v_monto;
    RETURN NEXT;
  END LOOP;
  RETURN;
END $$;

-- Viajes futuros de una frecuencia que ya tienen pasajeros (para que el front avise antes de quitarla).
DROP FUNCTION IF EXISTS fn_viajes_futuros_con_pasajeros(INT) CASCADE;
CREATE FUNCTION fn_viajes_futuros_con_pasajeros(p_id_frecuencia INT)
RETURNS TABLE (id_viaje INT, fecha_utc DATE, inicio_utc TIMESTAMPTZ, boletos_activos BIGINT)
LANGUAGE sql STABLE AS $$
  SELECT v.id_viaje, v.fecha_utc, v.inicio_utc, count(*)
  FROM viaje v JOIN boleto b ON b.id_viaje = v.id_viaje AND b.estado = 'ACTIVO'
  WHERE v.id_frecuencia = p_id_frecuencia AND v.estado = 'PROGRAMADO' AND v.inicio_utc > now()
  GROUP BY v.id_viaje
  ORDER BY v.inicio_utc;
$$;

-- Quita una frecuencia: la deshabilita y trata sus viajes futuros (PROGRAMADO).
--  * sin boletos            -> se eliminan
--  * con boletos            -> solo si p_forzar = TRUE; se cancelan con reembolso (fn_cancelar_viaje)
-- Devuelve las reservas afectadas para notificar por correo (no hay pasarela de pago en esta versión).
-- Los viajes ya en curso o pasados no se tocan.
DROP FUNCTION IF EXISTS fn_deshabilitar_frecuencia(INT, BOOLEAN, VARCHAR) CASCADE;
CREATE FUNCTION fn_deshabilitar_frecuencia(p_id_frecuencia INT, p_forzar BOOLEAN DEFAULT FALSE,
                                           p_motivo VARCHAR DEFAULT 'Frecuencia eliminada por la empresa')
RETURNS TABLE (r_id_reserva INT, r_codigo_reserva VARCHAR, r_correo VARCHAR, r_monto_reembolso NUMERIC)
LANGUAGE plpgsql AS $$
DECLARE vj RECORD;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM frecuencia WHERE id_frecuencia = p_id_frecuencia) THEN
    RAISE EXCEPTION 'Frecuencia % no existe', p_id_frecuencia;
  END IF;
  IF NOT p_forzar AND EXISTS (SELECT 1 FROM fn_viajes_futuros_con_pasajeros(p_id_frecuencia)) THEN
    RAISE EXCEPTION 'La frecuencia % tiene viajes futuros con pasajeros; confirma para cancelarlos y reembolsar', p_id_frecuencia;
  END IF;

  UPDATE frecuencia SET esta_habilitado = FALSE WHERE id_frecuencia = p_id_frecuencia;

  FOR vj IN
    SELECT v.id_viaje, EXISTS (SELECT 1 FROM boleto b WHERE b.id_viaje = v.id_viaje) AS tiene_boletos
    FROM viaje v
    WHERE v.id_frecuencia = p_id_frecuencia AND v.estado = 'PROGRAMADO' AND v.inicio_utc > now()
  LOOP
    IF vj.tiene_boletos THEN
      RETURN QUERY SELECT * FROM fn_cancelar_viaje(vj.id_viaje, p_motivo);
    ELSE
      DELETE FROM viaje WHERE id_viaje = vj.id_viaje;   -- las paradas caen en cascada
    END IF;
  END LOOP;
  RETURN;
END $$;

